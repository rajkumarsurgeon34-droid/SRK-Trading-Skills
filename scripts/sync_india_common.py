"""Copy india_common/ (helpers + config) into every skill's scripts/ folder.

Run after editing india_common/india_fno_config.json or india_common.py:
    python3 scripts/sync_india_common.py
"""
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "india_common"
FILES = ["india_common.py", "india_fno_config.json"]

count = 0
for scripts in sorted((ROOT / "skills").glob("*/scripts")):
    if not any(scripts.glob("*.py")):
        continue
    for f in FILES:
        shutil.copy2(SRC / f, scripts / f)
    count += 1
print(f"Synced india_common into {count} skills.")

# Mobile app: same config as an ES module
app_cfg = ROOT / "android-app" / "app" / "src" / "main" / "assets" / "www" / "js" / "config.js"
if app_cfg.parent.exists():
    import json as _json
    data = _json.loads((SRC / "india_fno_config.json").read_text(encoding="utf-8"))
    app_cfg.write_text(
        "// GENERATED by scripts/sync_india_common.py from india_common/india_fno_config.json — do not edit\n"
        "export const CONFIG = " + _json.dumps(data, indent=1, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print("Synced config into the mobile app.")
